//! Existing numeric section locks retain their history across report spelling
//! corrections (§FS-section-lock.write.never-a-move, §FS-config.3.2.8).

#[path = "support/numeric_spelling.rs"]
#[allow(dead_code)]
mod support;

use support::Repo;

const ORIGINAL: &str =
    "# ADR-0001: Decision\n\n## 1. Overview\n\n### .1. Goals\n\nOriginal goals.\n";
const MOVED: &str = "# ADR-0001: Decision\n\n## 1. Overview\n\n### .1. Other\n\nDifferent goals.\n\n### .2. Goals\n\nOriginal goals.\n";
const LOCK_CHECK: &[&str] = &[
    "check",
    "--only",
    "unrecorded-section-citation",
    "--only",
    "section-address-changed",
];

/// Baseline binaries used three digits by default and no padding for a kind
/// override. Neither spelling permits fmt to forget a recorded text's move.
#[test]
fn baseline_numeric_locks_survive_unchanged_and_moved_sections_before_and_after_fmt() {
    for version in [1, 2] {
        for per_kind in [false, true] {
            for old_id in ["ADR-001", "ADR-1"] {
                for citation in ["ADR-0001", "ADR-001", "ADR-1"] {
                    let repo = Repo::new(version, per_kind);
                    repo.write("docs/adr/ADR-0001.md", ORIGINAL);
                    repo.write("docs/notes.md", &format!("See \u{a7}{citation}.1.1.\n"));
                    let path = format!(".grund/sections/{old_id}.lock");
                    // The fingerprint recorded by the baseline, not generated by
                    // the renderer under test (review-1's upgrade reproducer).
                    let recorded = format!("{old_id}.1.1 e667f43b7482e88a\n");
                    repo.write(&path, &recorded);
                    repo.run(LOCK_CHECK, 0);
                    repo.run(&["fmt", "--write"], 0);
                    assert_eq!(repo.read(&path), recorded);
                    repo.run(LOCK_CHECK, 0);

                    repo.write("docs/adr/ADR-0001.md", MOVED);
                    for _ in 0..2 {
                        let report = repo.run(LOCK_CHECK, 1);
                        assert!(
                            report.contains(&format!("now sits at {old_id}.1.2")),
                            "{report}"
                        );
                        assert!(!report.contains("has no entry"), "{report}");
                        repo.run(&["fmt", "--write"], 0);
                        assert_eq!(repo.read(&path), recorded);
                    }
                    repo.run(LOCK_CHECK, 1);
                    let locks = std::fs::read_dir(repo.root.join(".grund/sections"))
                        .unwrap()
                        .map(|entry| entry.unwrap().file_name())
                        .collect::<Vec<_>>();
                    assert_eq!(locks, [std::ffi::OsString::from(format!("{old_id}.lock"))]);
                }
            }
        }
    }
}
